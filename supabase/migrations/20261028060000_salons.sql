-- Office-only until the CTL-18 OTP flow (P1-02 part c): set or replace the primary phone.
create function app.office_set_primary_contact(p_salon_id uuid, p_name text, p_phone text, p_reason text)
returns public.salon_contact
language plpgsql security definer set search_path = '' as $$
declare v public.salon_contact;
begin
  perform app.assert_office();
  perform app.assert_reason(p_reason);
  if not exists (select 1 from public.salon where id = p_salon_id) then
    raise exception using errcode = '22023', message = 'unknown salon';
  end if;
  perform app.set_purpose('primary contact changed: ' || p_reason);
  update public.salon_contact set is_primary = false, active = false
   where salon_id = p_salon_id and is_primary and active;
  insert into public.salon_contact (salon_id, name, phone, created_by)
  values (p_salon_id, nullif(btrim(p_name), ''), p_phone, auth.uid())
  returning * into v;
  return v;
end $$;

