-- ------------------------------------------------------------------- guards ----
create function control.rep_territory_guard() returns trigger
language plpgsql set search_path = '' as $$
begin
  if tg_op = 'DELETE' then
    raise exception using errcode = '42501', message = 'territory assignments are ended, never deleted';
  end if;
  if old.to_date is not null then
    raise exception using errcode = '42501', message = 'an ended territory assignment is final';
  end if;
  if (new.id, new.rep_id, new.territory_id, new.from_date, new.assigned_by, new.created_at)
     is distinct from (old.id, old.rep_id, old.territory_id, old.from_date, old.assigned_by, old.created_at)
     or new.to_date is null then
    raise exception using errcode = '42501', message = 'a territory assignment changes only by being ended';
  end if;
  return new;
end $$;

-- Salon identity is immutable; the stage moves only with a stage_event in the same transaction.
create function control.salon_guard() returns trigger
language plpgsql set search_path = '' as $$
begin
  if tg_op = 'DELETE' then
    raise exception using errcode = '42501', message = 'salons are never deleted (H-07); park them instead';
  end if;
  if (new.id, new.created_by, new.created_at, new.source, new.discovered_by, new.created_at_client)
     is distinct from (old.id, old.created_by, old.created_at, old.source, old.discovered_by, old.created_at_client) then
    raise exception using errcode = '42501', message = 'salon identity columns are immutable';
  end if;
  if new.stage is distinct from old.stage and not exists (
       select 1 from public.stage_event e
       where e.salon_id = new.id and e.from_stage = old.stage and e.to_stage = new.stage
         and e.tx_id = txid_current()) then
    raise exception using errcode = '42501', message = 'a salon''s stage changes only with a stage_event (doc 04)';
  end if;
  if new.verification_status is distinct from old.verification_status then
    raise exception using errcode = '42501', message = 'verification changes only through the CTL-09 flow';
  end if;
  new.updated_at := now();
  return new;
end $$;

create function control.salon_contact_guard() returns trigger
language plpgsql set search_path = '' as $$
begin
  if tg_op = 'DELETE' then
    raise exception using errcode = '42501', message = 'contacts are deactivated, never deleted (H-07)';
  end if;
  if (new.id, new.salon_id, new.created_by, new.created_at)
     is distinct from (old.id, old.salon_id, old.created_by, old.created_at) then
    raise exception using errcode = '42501', message = 'contact identity columns are immutable';
  end if;
  new.updated_at := now();
  return new;
end $$;

