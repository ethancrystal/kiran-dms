-- doc 06 §4: one phone for one salon, and the reveal is logged.
create function app.reveal_phone(p_salon_id uuid)
returns text
language plpgsql security definer set search_path = '' as $$
declare
  v_role public.app_role := app.assert_actor_ready();
  c      public.salon_contact;
begin
  if v_role = 'rep' and not app.rep_can_reach_salon(p_salon_id) then
    perform app.raise_denied('reps reveal phones only for salons in their own territories');
  end if;
  if v_role in ('owner', 'manager') and not app.is_office() then
    perform app.raise_denied('office actions require an MFA-verified (AAL2) session');
  end if;
  select * into c from public.salon_contact where salon_id = p_salon_id and is_primary and active;
  if c.id is null then return null; end if;
  if v_role = 'rep' then
    insert into control.phone_reveal (salon_id, contact_id, actor_id) values (p_salon_id, c.id, auth.uid());
  end if;
  return c.phone;
end $$;

-- CTL-18 part: phones on more than one active salon (the digest lists these, P1-08).
create function app.duplicate_phones()
returns table (phone text, salon_ids uuid[])
language plpgsql stable security definer set search_path = '' as $$
begin
  perform app.assert_office();
  return query
    select c.phone, array_agg(distinct c.salon_id order by c.salon_id)
    from public.salon_contact c where c.active
    group by c.phone having count(distinct c.salon_id) > 1
    order by c.phone;
end $$;

-- Lost demand (migration 0008) may name a salon: reps only one they can reach.
create or replace function app.record_demand(
  p_client_id uuid, p_sku_id uuid, p_product_group_id uuid, p_qty integer, p_reason public.demand_reason,
  p_salon_id uuid default null, p_captured_at_client timestamptz default null)
returns public.demand_signal
language plpgsql security definer set search_path = '' as $$
declare
  v_role public.app_role := app.assert_actor_ready();
  v      public.demand_signal;
begin
  select * into v from public.demand_signal where client_id = p_client_id;
  if v.id is not null then
    if v.captured_by = auth.uid() and v.sku_id is not distinct from p_sku_id
       and v.product_group_id is not distinct from p_product_group_id
       and v.qty = p_qty and v.reason = p_reason then
      return v;                                                             -- idempotent replay
    end if;
    raise exception using errcode = '23505', message = 'client_id already used with different content';
  end if;
  if p_reason = 'supply_short' and v_role = 'rep' then
    perform app.raise_denied('reps record out_of_stock; supply shortages are recorded by the office');
  end if;
  if p_salon_id is not null and v_role = 'rep' and not app.rep_can_reach_salon(p_salon_id) then
    perform app.raise_denied('reps record demand only for salons in their own territories');
  end if;
  perform app.set_purpose('lost demand: ' || p_reason::text);
  insert into public.demand_signal (client_id, sku_id, product_group_id, qty, reason, source, salon_id,
                                    location_id, captured_by, captured_at_client)
  values (p_client_id, p_sku_id, p_product_group_id, p_qty, p_reason, 'visit_tap', p_salon_id,
          app.my_bag_id(), auth.uid(), p_captured_at_client)
  returning * into v;
  return v;
end $$;

