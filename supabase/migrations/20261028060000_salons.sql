-- ------------------------------------------------------------ scope helpers ----
-- Territories the calling rep holds today.
create function app.my_territory_ids() returns setof uuid
language sql stable security definer set search_path = '' as $$
  select rt.territory_id from public.rep_territory rt
  where rt.rep_id = auth.uid() and rt.to_date is null and app.user_role() = 'rep'
$$;

-- True when the calling rep may act on this salon: an active rep on the approved device whose
-- current territories include the salon's area's territory (doc 06 §4).
create function app.rep_can_reach_salon(p_salon_id uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select app.self_ok() and app.user_role() = 'rep' and exists (
    select 1 from public.salon s join public.area a on a.id = s.area_id
    where s.id = p_salon_id and a.territory_id in (select app.my_territory_ids()))
$$;

create function app.rep_can_use_area(p_area_id uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select app.self_ok() and app.user_role() = 'rep' and exists (
    select 1 from public.area a join public.territory t on t.id = a.territory_id
    where a.id = p_area_id and a.active and t.active and a.territory_id in (select app.my_territory_ids()))
$$;

-- '+920000001234' → '+920*******34': enough to recognise, not enough to call (synthetic example, H-03).
create function app.mask_phone(p_phone text) returns text
language sql immutable set search_path = '' as $$
  select case when p_phone is null then null
              else left(p_phone, 4) || repeat('*', greatest(length(p_phone) - 6, 0)) || right(p_phone, 2) end
$$;

-- Internal: the only path that moves a stage. Writes the event, then the mirror.
create function app.move_stage(p_salon_id uuid, p_to public.salon_stage, p_trigger public.stage_trigger, p_reason text)
returns public.salon
language plpgsql security definer set search_path = '' as $$
declare v public.salon;
begin
  select * into v from public.salon where id = p_salon_id for update;
  if v.id is null then raise exception using errcode = '22023', message = 'unknown salon'; end if;
  if v.stage = p_to then return v; end if;
  insert into public.stage_event (salon_id, from_stage, to_stage, trigger, reason, actor_id)
  values (p_salon_id, v.stage, p_to, p_trigger, p_reason, auth.uid());
  update public.salon set stage = p_to where id = p_salon_id returning * into v;
  return v;
end $$;

-- ------------------------------------------------------ territory functions ----
create function app.office_upsert_territory(p_id uuid, p_name text, p_active boolean default true)
returns public.territory
language plpgsql security definer set search_path = '' as $$
declare v public.territory;
begin
  perform app.assert_office();
  perform app.set_purpose('territory');
  insert into public.territory as t (id, name, active, created_by)
  values (p_id, p_name, coalesce(p_active, true), auth.uid())
  on conflict (id) do update set name = excluded.name, active = excluded.active
  returning * into v;
  return v;
end $$;

create function app.office_upsert_area(p_id uuid, p_territory_id uuid, p_name text, p_active boolean default true)
returns public.area
language plpgsql security definer set search_path = '' as $$
declare v public.area;
begin
  perform app.assert_office();
  perform app.set_purpose('area');
  insert into public.area as a (id, territory_id, name, active, created_by)
  values (p_id, p_territory_id, p_name, coalesce(p_active, true), auth.uid())
  on conflict (id) do update set territory_id = excluded.territory_id, name = excluded.name, active = excluded.active
  returning * into v;
  return v;
end $$;

create function app.office_assign_territory(p_rep_id uuid, p_territory_id uuid)
returns public.rep_territory
language plpgsql security definer set search_path = '' as $$
declare v public.rep_territory;
begin
  perform app.assert_office();
  if not exists (select 1 from public.user_profile u where u.id = p_rep_id and u.role = 'rep' and u.status = 'active') then
    raise exception using errcode = '22023', message = 'territories are assigned to active reps';
  end if;
  select * into v from public.rep_territory where rep_id = p_rep_id and territory_id = p_territory_id and to_date is null;
  if v.id is not null then return v; end if;                                -- already assigned
  perform app.set_purpose('territory assigned');
  insert into public.rep_territory (rep_id, territory_id, assigned_by)
  values (p_rep_id, p_territory_id, auth.uid()) returning * into v;
  return v;
end $$;

create function app.office_end_territory(p_rep_id uuid, p_territory_id uuid, p_reason text)
returns public.rep_territory
language plpgsql security definer set search_path = '' as $$
declare v public.rep_territory;
begin
  perform app.assert_office();
  perform app.assert_reason(p_reason);
  perform app.set_purpose('territory ended: ' || p_reason);
  update public.rep_territory
     set to_date = (now() at time zone 'Asia/Karachi')::date, ended_by = auth.uid()
   where rep_id = p_rep_id and territory_id = p_territory_id and to_date is null
  returning * into v;
  if v.id is null then raise exception using errcode = '22023', message = 'no current assignment for this rep and territory'; end if;
  return v;
end $$;

-- ---------------------------------------------------------- salon functions ----
-- SAL-01 / PIP-07: create a salon (prospect). Reps only in their own territories and only
-- from the field sources; idempotent on the client-generated id.
create function app.create_salon(
  p_id uuid, p_name text, p_type public.salon_type, p_area_id uuid, p_source public.salon_source,
  p_address text default null, p_lat numeric default null, p_lng numeric default null, p_chairs integer default null,
  p_contact_name text default null, p_contact_phone text default null, p_note text default null,
  p_created_at_client timestamptz default null)
returns public.salon
language plpgsql security definer set search_path = '' as $$
declare
  v_role public.app_role := app.assert_actor_ready();
  v      public.salon;
begin
  select * into v from public.salon where id = p_id;
  if v.id is not null then
    if v.created_by = auth.uid() and v.area_id = p_area_id and v.type = p_type then return v; end if;  -- replay
    raise exception using errcode = '23505', message = 'salon id already used';
  end if;
  if v_role = 'rep' then
    if not app.rep_can_use_area(p_area_id) then
      perform app.raise_denied('reps add salons only in their own territories');
    end if;
    if p_source not in ('map_pin', 'sweep', 'referral', 'manual') then
      perform app.raise_denied('reps add salons from the field only');
    end if;
  elsif not exists (select 1 from public.area where id = p_area_id) then
    raise exception using errcode = '22023', message = 'unknown area';
  end if;
  perform app.set_purpose('salon created');
  insert into public.salon (id, name, type, area_id, address, lat, lng, chairs, source, discovered_by, created_by,
                            created_at_client)
  values (p_id, nullif(btrim(p_name), ''), p_type, p_area_id, p_address, p_lat, p_lng, p_chairs, p_source,
          auth.uid(), auth.uid(), p_created_at_client)
  returning * into v;
  insert into public.stage_event (salon_id, from_stage, to_stage, trigger, actor_id)
  values (v.id, null, 'prospect', 'created', auth.uid());
  if p_contact_phone is not null then
    insert into public.salon_contact (salon_id, name, phone, created_by)
    values (v.id, nullif(btrim(p_contact_name), ''), p_contact_phone, auth.uid());
  end if;
  if p_note is not null and length(btrim(p_note)) > 0 then
    insert into public.salon_note (client_id, salon_id, author_id, body, created_at_client)
    values (gen_random_uuid(), v.id, auth.uid(), p_note, p_created_at_client);
  end if;
  return v;
end $$;

-- Edit the descriptive fields. A rep may move a salon only between areas of their territories.
create function app.update_salon(
  p_id uuid, p_name text, p_type public.salon_type, p_area_id uuid,
  p_address text default null, p_lat numeric default null, p_lng numeric default null, p_chairs integer default null)
returns public.salon
language plpgsql security definer set search_path = '' as $$
declare
  v_role public.app_role := app.assert_actor_ready();
  v      public.salon;
begin
  if v_role = 'rep' then
    if not app.rep_can_reach_salon(p_id) or not app.rep_can_use_area(p_area_id) then
      perform app.raise_denied('reps edit salons only in their own territories');
    end if;
  elsif v_role not in ('owner', 'manager') or not app.is_office() then
    perform app.raise_denied('owner or manager only');
  end if;
  perform app.set_purpose('salon edited');
  update public.salon
     set name = nullif(btrim(p_name), ''), type = p_type, area_id = p_area_id, address = p_address,
         lat = p_lat, lng = p_lng, chairs = p_chairs
   where id = p_id returning * into v;
  if v.id is null then raise exception using errcode = '22023', message = 'unknown salon'; end if;
  return v;
end $$;

-- MAP-03: append a note (the chit). Idempotent on client_id.
create function app.add_salon_note(p_client_id uuid, p_salon_id uuid, p_body text, p_created_at_client timestamptz default null)
returns public.salon_note
language plpgsql security definer set search_path = '' as $$
declare
  v_role public.app_role := app.assert_actor_ready();
  v      public.salon_note;
begin
  select * into v from public.salon_note where client_id = p_client_id;
  if v.id is not null then
    if v.author_id = auth.uid() and v.salon_id = p_salon_id and v.body = p_body then return v; end if;
    raise exception using errcode = '23505', message = 'client_id already used with different content';
  end if;
  if v_role = 'rep' and not app.rep_can_reach_salon(p_salon_id) then
    perform app.raise_denied('reps add notes only to salons in their own territories');
  end if;
  if not exists (select 1 from public.salon where id = p_salon_id) then
    raise exception using errcode = '22023', message = 'unknown salon';
  end if;
  perform app.set_purpose('salon note');
  insert into public.salon_note (client_id, salon_id, author_id, body, created_at_client)
  values (p_client_id, p_salon_id, auth.uid(), p_body, p_created_at_client)
  returning * into v;
  return v;
end $$;

-- doc 02: a rep parks a salon that is not interested now (from the acquisition stages only).
create function app.rep_park_salon(p_salon_id uuid, p_reason text)
returns public.salon
language plpgsql security definer set search_path = '' as $$
declare
  v_role public.app_role := app.assert_actor_ready();
  v      public.salon;
begin
  if v_role <> 'rep' or not app.rep_can_reach_salon(p_salon_id) then
    perform app.raise_denied('reps park salons only in their own territories');
  end if;
  perform app.assert_reason(p_reason);
  select * into v from public.salon where id = p_salon_id;
  if v.stage = 'parked' then return v; end if;
  if v.stage not in ('prospect', 'visited', 'trial') then
    perform app.raise_denied('only prospects, visited and trial salons can be parked by a rep');
  end if;
  perform app.set_purpose('salon parked: ' || p_reason);
  return app.move_stage(p_salon_id, 'parked', 'manual', p_reason);
end $$;

